async function seedAbujaVendors() {
  try {
    await mongoose.connect(process.env.MONGODB_URI);
    console.log("Connected to MongoDB");

    // Clear existing Abuja vendors
    await Vendor.deleteMany({ "address.city": "Abuja" });
    console.log("Cleared existing Abuja vendors");

    // Insert vendors
    const result = await Vendor.insertMany(vendors);
    console.log(`✅ Successfully seeded ${result.length} Abuja vendors`);

    // Display summary
    const summary = {};
    result.forEach((vendor) => {
      summary[vendor.category] = (summary[vendor.category] || 0) + 1;
    });

    console.log("\nVendors by Category:");
    Object.entries(summary).forEach(([category, count]) => {
      console.log(`  - ${category}: ${count} vendors`);
    });

    process.exit(0);
  } catch (error) {
    console.error("❌ Error seeding Abuja vendors:", error);
    process.exit(1);
  }
}

seedAbujaVendors();
